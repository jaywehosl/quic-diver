// Package procmatch сопоставляет поток с процессом, который его открыл.
//
// Нужно для правил вида «торрент — через выход, браузер — напрямую». Приложение о себе
// ничего не сообщает, поэтому узнавать приходится у операционной системы: по адресам
// соединения найти сокет, по сокету — процесс.
//
// # Чего это стоит
//
// На Linux ответ собирается из /proc: сперва в таблице соединений ищется инод сокета, затем
// перебираются дескрипторы процессов, пока не найдётся ссылка на этот инод. Второй шаг —
// обход сотен каталогов, и делать его на каждый поток нельзя. Поэтому соответствие
// «инод → процесс» кешируется: у процесса за время жизни соединения имя не меняется.
//
// # Почему интерфейс, а не функция
//
// На Windows источник другой — таблица соединений из iphlpapi, — и подставляется он тем же
// интерфейсом. Правило `process:` при этом остаётся одним и тем же во всех сборках.
package procmatch

import (
	"errors"
	"net/netip"
)

// ErrNotFound означает, что процесс определить не удалось.
//
// Это не поломка: соединение могло закрыться, пока мы искали, а сам поиск может быть
// недоступен по правам. Правило `process:` просто не сработает, остальные отработают как
// обычно.
var ErrNotFound = errors.New("procmatch: процесс не найден")

// ErrUnsupported означает, что на этой платформе поиск не реализован.
var ErrUnsupported = errors.New("procmatch: определение процесса не поддерживается на этой платформе")

// Finder находит процесс по концам соединения.
type Finder interface {
	// Lookup возвращает имя процесса, открывшего соединение с такими концами.
	Lookup(local, remote netip.AddrPort) (string, error)
}

// nopFinder ничего не находит. Им пользуются платформы без поддержки и тесты.
type nopFinder struct{}

func (nopFinder) Lookup(netip.AddrPort, netip.AddrPort) (string, error) {
	return "", ErrUnsupported
}

// Nop возвращает искатель, который всегда отвечает «не знаю».
func Nop() Finder { return nopFinder{} }
