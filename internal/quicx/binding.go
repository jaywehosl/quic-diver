package quicx

import (
	"crypto/tls"
	"errors"
	"fmt"
)

// Привязка к TLS-сессии.
//
// Приветствие «свой-чужой» подписывает не произвольный вызов, а секрет, выведенный из
// конкретного рукопожатия (RFC 5705 в редакции TLS 1.3, тот же приём, что в RFC 9266).
// Обе стороны получают его одинаковым, наблюдатель — никак: он выводится из ключей сессии.
//
// Что это даёт: подписанное приветствие невозможно ретранслировать. Ни в соединение с другим
// узлом, ни во второе соединение с тем же самым — там будет другой секрет, и подпись не
// сойдётся. Привязка к отпечатку сертификата такой стойкости не даёт: сертификат один и тот
// же во всех сессиях узла, поэтому перехваченное приветствие годилось бы повторно.

const (
	// bindingLabel — метка экспортёра. Своя метка отделяет наши подписи от любых других,
	// выводимых из той же сессии.
	bindingLabel = "EXPORTER-qdiver-hello-v1"
	// bindingLen — длина привязки. 32 байта — размер выхода SHA-256, больше смысла не несёт.
	bindingLen = 32
)

// ErrNoBinding означает, что рукопожатие ещё не завершено: до этого момента экспортёр
// ключей не готов, и подписывать нечего.
var ErrNoBinding = errors.New("quicx: привязка к сессии недоступна — рукопожатие не завершено")

// Binding возвращает привязку к TLS-сессии.
func Binding(state tls.ConnectionState) ([]byte, error) {
	if !state.HandshakeComplete {
		return nil, ErrNoBinding
	}
	b, err := state.ExportKeyingMaterial(bindingLabel, nil, bindingLen)
	if err != nil {
		return nil, fmt.Errorf("quicx: вывод привязки к сессии: %w", err)
	}
	return b, nil
}
