package node

import (
	"context"
	"sync"

	"github.com/quic-go/quic-go"
)

// Смена потолка BRUTAL на живых соединениях (решение 006).
//
// # Зачем
//
// Потолок задаёт человек и меняет его на работающей сети. Единственным способом донести новое
// число до узла был перезапуск службы — а он рвёт все соединения разом, то есть роняет трафик
// всех клиентов ради двух байт в журнале.
//
// Между тем вся скорость BRUTAL держится на одном числе внутри контроллера: пейсер читает его
// на каждом такте, окно пересчитывается из него же. Значит менять его можно прямо на ходу —
// соединение не заметит ничего, кроме новой скорости.
//
// # Чего это не умеет
//
// Включить BRUTAL там, где его не было. Контроллер выбирается при рукопожатии: соединение,
// установленное на обычном Cubic, таким и останется до переподключения. Поэтому потолок и
// приезжает узлу ключом развёртывания — чтобы он поднялся с BRUTAL с самого начала, а не после
// первой правки журнала.

// conns — живые соединения узла.
//
// Реестр нужен ровно для одного: обойти их, когда потолок изменился. Ничего другого узел о
// соединениях не помнит — их время жизни держит quic-go, а не мы.
type conns struct {
	mu   sync.Mutex
	live map[*quic.Conn]struct{}
}

func newConns() *conns {
	return &conns{live: make(map[*quic.Conn]struct{})}
}

// track берёт соединение на учёт и снимает его, когда оно кончится.
//
// Снятие идёт своей горутиной, ждущей закрытия: у quic-go нет обратного вызова на смерть
// соединения, а без снятия карта росла бы всё время работы узла.
func (c *conns) track(qc *quic.Conn) {
	c.mu.Lock()
	c.live[qc] = struct{}{}
	c.mu.Unlock()

	go func() {
		<-qc.Context().Done()
		c.mu.Lock()
		delete(c.live, qc)
		c.mu.Unlock()
	}()
}

// each обходит живые соединения.
func (c *conns) each(fn func(*quic.Conn)) int {
	c.mu.Lock()
	list := make([]*quic.Conn, 0, len(c.live))
	for qc := range c.live {
		list = append(list, qc)
	}
	c.mu.Unlock()

	// Обход вне замка: SetBrutalSendMbps идёт внутрь quic-go, и держать там свой мьютекс —
	// верный способ однажды получить взаимную блокировку на ровном месте.
	for _, qc := range list {
		fn(qc)
	}
	return len(list)
}

// SetSendMbps меняет потолок отправки на всех соединениях узла и на будущих.
//
// Отвечает, скольких живых соединений это коснулось. Ноль означает, что менять было нечего, —
// не ошибка: узел мог просто никого не обслуживать в этот момент.
func (n *Node) SetSendMbps(mbps int) int {
	if mbps <= 0 {
		return 0
	}
	n.sendMbps.Store(int64(mbps))
	return n.conns.each(func(qc *quic.Conn) { qc.SetBrutalSendMbps(mbps) })
}

// connContext берёт соединение на учёт и выставляет ему действующий потолок.
//
// Потолок выставляется здесь, а не только в настройках слушателя, потому что настройки
// слушателя зафиксированы при запуске: соединение, пришедшее после правки журнала, получило бы
// старое число.
func (n *Node) connContext(ctx context.Context, qc *quic.Conn) context.Context {
	n.conns.track(qc)
	if mbps := n.sendMbps.Load(); mbps > 0 {
		qc.SetBrutalSendMbps(int(mbps))
	}
	return ctx
}
