package node

import (
	"crypto/sha256"
	"crypto/subtle"
	"strings"

	"github.com/jaywehosl/quic-diver/internal/oplog"
)

// Код узла — короткий отпечаток его публичного ключа.
//
// # Зачем
//
// Свежий узел называет свой ключ по сети, и это единственное, чем он себя подтверждает. TLS
// доказывает только владение доменом — а тот, кто на пять минут получил власть над DNS, выпишет
// себе сертификат и ответит своим ключом. Клиент послушно впишет чужой узел в журнал.
//
// Код разрывает эту зависимость. Скрипт печатает его прямо на сервере, в терминале того, кто
// узел разворачивал; человек переносит восемь знаков в приложение, и приложение сверяет их с
// тем, что получило по сети. Подделавший ответ кода не знает — он напечатан там, куда
// подделавший не заглядывает.
//
// # Почему код считается из ключа, а не берётся случайным
//
// Случайный код узлу пришлось бы передавать тем же путём, что и ключ. Кто подделал одно,
// подделал бы и второе — проверка выродилась бы в сверку ответа с самим собой.
//
// Отпечаток так не обмануть: чтобы ответ сошёлся, нужна ключевая пара, дающая ровно эти сорок
// бит. Подобрать её перебором можно, но узнать целевой код неоткуда — он на чужом экране, а
// каждая попытка обмана видна человеку как несовпадение.
//
// # Почему сорок бит хватает
//
// Код — не секрет и не пароль: он публичен по сути, ротации не требует и живёт ровно одну
// минуту, пока идёт включение узла. Единственная его работа — не дать подставиться тому, кто
// перехватил домен, а тому неоткуда узнать, что печатать. Восемь знаков переносятся без
// ошибок; шестьдесят четыре знака ключа человек переписал бы неверно, и никто бы не заметил.

// codeAlphabet — алфавит Кроукфорда: без I, L, O и U.
//
// Первые три выброшены потому, что их путают с единицей и нулём, — а код переносят руками, с
// экрана на экран. U выброшена, чтобы из кода случайно не сложилось бранное слово.
const codeAlphabet = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"

// CodeLength — сколько знаков в коде. Восемь знаков алфавита из 32 — это сорок бит.
const CodeLength = 8

// Code считает код узла по его публичному ключу.
//
// Показывается парами по четыре знака: 3F7K-92QW. Разделитель при сверке отбрасывается.
func Code(pub oplog.PublicKey) string {
	sum := sha256.Sum256(pub)

	var b strings.Builder
	b.Grow(CodeLength + 1)
	for i := 0; i < CodeLength; i++ {
		if i == CodeLength/2 {
			b.WriteByte('-')
		}
		b.WriteByte(codeAlphabet[sum[i]%byte(len(codeAlphabet))])
	}
	return b.String()
}

// NormalizeCode приводит код к виду, в котором его можно сравнивать.
//
// Человек введёт его как придётся: строчными, с пробелом посередине, без дефиса или с двумя.
// Отказывать из-за этого — значит заставить его вводить заново то, что он и так ввёл верно.
func NormalizeCode(s string) string {
	var b strings.Builder
	b.Grow(CodeLength)
	for _, r := range strings.ToUpper(strings.TrimSpace(s)) {
		if strings.ContainsRune(codeAlphabet, r) {
			b.WriteRune(r)
		}
	}
	return b.String()
}

// CodeMatches сверяет введённый код с кодом ключа.
//
// Сравнение постоянного времени. Секретом код не является, и утечка по времени ничего бы не
// дала, — но правило «ключевые сравнения делаются так» стоит соблюдать всюду, иначе однажды
// оно не соблюдётся там, где это важно.
func CodeMatches(pub oplog.PublicKey, entered string) bool {
	want := NormalizeCode(Code(pub))
	got := NormalizeCode(entered)
	if len(got) != len(want) {
		return false
	}
	return subtle.ConstantTimeCompare([]byte(want), []byte(got)) == 1
}
