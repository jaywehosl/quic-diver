package node

import (
	"encoding/json"
	"io"
	"net/http"

	"github.com/jaywehosl/quic-diver/internal/oplog"
)

// Первый залив журнала в пустой узел.
//
// # Зачем отдельный путь
//
// Развёрнутый узел не знает ничего: журнала у него нет, а значит нет ни ключей владельцев, ни
// клиентов, ни соседей. Опознать пришедшего ему нечем — приветствие проверять не по чему, и
// любой, кто постучится на управляющий канал, получит заглушку. Круг замкнулся: чтобы принять
// журнал, нужен журнал.
//
// # Почему это безопасно
//
// Разрывает круг отпечаток сети. Он лежит в конфиге узла — его вписал туда тот, кто узел
// разворачивал, — и журнал принимается, только если его генезис даёт ровно этот отпечаток.
// Подделать такой журнал нельзя: отпечаток считается по подписанной записи генезиса, и без
// ключа владельца собрать её не выйдет.
//
// То есть проверка та же, что и у соседей при первом знакомстве (решение 001, mesh.bootstrap):
//
//	Ключ соседа здесь не проверяется — его неоткуда взять. Защита в другом: журнал подписан,
//	а отпечаток сети записан у нас в конфиге, поэтому подсунуть свою сеть посторонний не может.
//
// # Когда путь закрывается
//
// Как только журнал принят. Дальше узел знает владельцев и разговаривает только с теми, кто
// предъявил подпись; повторный залив этим путём получает ту же заглушку, что и посторонний.

// BootstrapPath — путь первого залива журнала.
//
// Секретом не является, как и управляющий канал: на пустом узле он ничего не даёт без журнала
// с нужным отпечатком, а на живом — не работает вовсе.
const BootstrapPath = "/qd/v1/bootstrap"

// maxBootstrap ограничивает размер первого залива.
//
// Журнал молодой сети — это генезис и несколько записей; мегабайта хватает с запасом. Ограничение
// нужно потому, что данные приходят от стороны, которая себя ничем не подтвердила.
const maxBootstrap = 1 << 20

// Importer принимает журнал целиком.
//
// За ним стоит хранилище узла. Отдельный интерфейс нужен затем, чтобы пакет node не зависел от
// store и чтобы залив можно было проверить без базы.
type Importer interface {
	// Genesis отдаёт отпечаток принятого генезиса. Нулевой означает, что журнала нет.
	Genesis() oplog.Fingerprint
	// Import вливает журнал из потока и отвечает, сколько записей принял.
	Import(r io.Reader) (int, error)
}

// Introduction — чем свежий узел представляется тому, кто пришёл его включать.
//
// Ключ здесь публичный, домен и имя человек и так только что вводил сам. Секретов нет ни
// одного, и появиться им неоткуда: журнала у узла нет, значит нет ни клиентов, ни соседей.
type Introduction struct {
	// ID — как узел зовут в его собственном конфиге.
	ID string `json:"id"`
	// Domain — имя, на которое выписан сертификат.
	Domain string `json:"domain"`
	// PublicKey — ключ узла. Ради него всё и затевалось: без ключа запись об узле в журнал не
	// написать, а сгенерировал его узел сам при первом запуске, и знать его больше некому.
	PublicKey oplog.PublicKey `json:"public_key"`
}

// serveIntroduce представляет узел, пока тот не в сети.
//
// Иначе включение узла упирается в яйцо и курицу: запись об узле подписывает владелец на своём
// устройстве, а публичный ключ узла рождается на сервере при первом запуске. Заставлять
// человека переносить шестьдесят четыре знака руками — верный способ получить опечатку там,
// где её никто не заметит до первого подключения.
func (n *Node) serveIntroduce(w http.ResponseWriter, r *http.Request) {
	if n.cfg.Import == nil || n.cfg.Introduce == nil {
		n.reject(w, r, "узел не готов представляться")
		return
	}
	if !n.cfg.Import.Genesis().IsZero() {
		n.reject(w, r, "узел уже в сети")
		return
	}

	body, err := json.Marshal(n.cfg.Introduce())
	if err != nil {
		n.reject(w, r, "представление не собралось")
		return
	}
	w.Header().Set("Content-Type", "application/json")
	w.Write(body)
}

// serveBootstrap принимает журнал, пока узел пуст.
func (n *Node) serveBootstrap(w http.ResponseWriter, r *http.Request) {
	if n.cfg.Import == nil {
		n.reject(w, r, "залив журнала не настроен")
		return
	}
	if !n.cfg.Import.Genesis().IsZero() {
		// Узел уже в сети. Отвечаем как на любой неизвестный путь: посторонний не должен по
		// разнице ответов понять, что этот адрес вообще что-то значит.
		n.reject(w, r, "журнал уже есть")
		return
	}

	body := http.MaxBytesReader(w, r.Body, maxBootstrap)
	defer body.Close()

	count, err := n.cfg.Import.Import(body)
	if err != nil {
		// Сюда попадает и главный случай: журнал не от нашей сети. Хранилище сверяет отпечаток
		// генезиса с тем, что записан в конфиге, и отвергает чужой.
		n.log.Warn("первый залив отклонён", "from", r.RemoteAddr, "err", err)
		n.reject(w, r, "журнал не принят")
		return
	}

	n.log.Info("журнал принят первым заливом",
		"from", r.RemoteAddr, "записей", count, "genesis", n.cfg.Import.Genesis().String())
	w.WriteHeader(http.StatusNoContent)
}
