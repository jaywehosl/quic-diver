package client

import (
	"log/slog"
	"os"
)

// fdGuard закрывает дескриптор интерфейса, если тот так и не стал туннелем.
//
// # Зачем
//
// На Android интерфейс заводит система, а приложение снимает с него владение (detachFd) и
// отдаёт номер сюда. С этой минуты закрыть дескриптор больше некому: ParcelFileDescriptor
// его отпустил, и никто, кроме нас, о нём не знает.
//
// Путь от Start до поднятого туннеля длинный: разобрать бандл, выиграть гонку входных узлов,
// дождаться первого соединения, загрузить правила. На каждом шаге можно выйти с ошибкой или
// по отмене — и до сих пор на всех этих путях дескриптор оставался открытым навсегда.
//
// Снаружи это выглядело так: человек нажимает «Подключить» и сразу «Отключить», в журнале
// честное «туннель снят», а значок VPN в строке состояния висит. Он и должен висеть: для
// системы интерфейс жив, пока жив его дескриптор.
//
// # Как пользоваться
//
// Завести сразу, как дескриптор получен, и закрыть через defer. Туннель, приняв дескриптор,
// объявляет об этом через taken — с этого мгновения владелец у номера снова один.
type fdGuard struct {
	fd    int
	log   *slog.Logger
	given bool
}

// newFDGuard берёт дескриптор под присмотр. Ноль означает, что присматривать не за чем:
// интерфейс клиент создаёт себе сам.
func newFDGuard(fd int, log *slog.Logger) *fdGuard {
	return &fdGuard{fd: fd, log: log}
}

// taken отмечает, что дескриптор принял туннель и дальше отвечает за него он.
func (g *fdGuard) taken() {
	if g != nil {
		g.given = true
	}
}

// close закрывает дескриптор, если тот остался ничьим.
func (g *fdGuard) close() {
	if g == nil || g.given || g.fd <= 0 {
		return
	}
	g.given = true

	// os.NewFile, а не syscall: то же самое, но без разделения по системам. Файл здесь
	// нужен ровно затем, чтобы его закрыть.
	if err := os.NewFile(uintptr(g.fd), "tun").Close(); err != nil {
		g.log.Warn("дескриптор интерфейса не закрылся", "fd", g.fd, "err", err)
		return
	}
	g.log.Info("интерфейс снят: до туннеля дело не дошло")
}
