// Package hwid — устойчивое имя устройства.
//
// Нужно ровно для одного: лимита «сколько устройств у клиента одновременно». Считать
// соединения вместо устройств нельзя — их у одного человека десятки, и гонка рукопожатий
// добавляет ещё по одному на каждый входной узел.
//
// # Чего это не даёт
//
// Идентификатор вычисляет сам клиент, а клиент под управлением человека. Подделать его,
// пересобрав программу, может любой, и никакая подпись этого не меняет: подписывать будет
// тот же ключ того же клиента. Поэтому лимит устройств — учёт для честных, а не защита от
// нечестных, и записано это здесь, а не выяснится потом.
//
// # Почему не сырой идентификатор машины
//
// Наружу уходит не machine-id, а его отпечаток вместе с постоянной меткой. Сырой
// идентификатор машины — общесистемное значение, по которому устройство узнаётся в других
// местах, и отдавать его сети незачем: нам нужно лишь отличать устройства друг от друга.
package hwid

import (
	"crypto/sha256"
	"encoding/hex"
	"os"
	"strings"
	"sync"
)

// domain отделяет наш отпечаток от любого другого использования того же идентификатора.
const domain = "qdiver-device-v1\x00"

// Length — длина отпечатка в шестнадцатеричных знаках.
//
// Шестнадцать знаков — восемь байт. Столкновение двух устройств одного клиента при таком
// размере невероятно, а короткая строка читается в журнале глазами.
const Length = 16

var (
	mu       sync.RWMutex
	supplied string
)

// Set задаёт идентификатор машины извне.
//
// Нужно там, где сама программа его добыть не может. На Android общесистемного файла нет
// вовсе: устойчивое значение живёт в Settings.Secure.ANDROID_ID, а достаётся оно вызовом
// через приложение — из Go туда хода нет. Без этого телефон приходил на узел безымянным, и
// лимит устройств на телефонах не работал совсем.
//
// Отпечаток снимается здесь же, как и с machine-id: наружу сырое значение не уходит.
func Set(raw string) {
	mu.Lock()
	supplied = strings.TrimSpace(raw)
	mu.Unlock()
}

// Get возвращает отпечаток устройства.
//
// Ошибку не возвращает намеренно: устройство, чей идентификатор не нашёлся, обязано
// работать — просто его не получится посчитать. Пустая строка означает ровно это, и лимит
// устройств такого клиента не режет.
func Get() string {
	mu.RLock()
	raw := supplied
	mu.RUnlock()

	if raw == "" {
		raw = machineID()
	}
	if raw == "" {
		return ""
	}
	sum := sha256.Sum256([]byte(domain + raw))
	return hex.EncodeToString(sum[:])[:Length]
}

// readFirst возвращает содержимое первого читаемого файла из списка.
func readFirst(paths ...string) string {
	for _, p := range paths {
		raw, err := os.ReadFile(p)
		if err != nil {
			continue
		}
		if s := strings.TrimSpace(string(raw)); s != "" {
			return s
		}
	}
	return ""
}
