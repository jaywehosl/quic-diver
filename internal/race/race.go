// Package race — гонка вход→выход по тёплым связям.
//
// Замысел из решения 001: входной узел не выбирает выходной по таблице, а спрашивает всех
// разом и отдаёт поток тому, кто первым откликнулся. Первым откликается тот, у кого сейчас
// меньше работы и короче путь, — то есть выбор делается по живому состоянию сети, а не по
// вчерашним замерам.
//
// # Почему это дёшево
//
// Гонка идёт по связям, которые уже установлены (см. internal/mesh), и стоит один RTT. Полное
// рукопожатие на каждый поток стоило бы столько же, сколько сам запрос пользователя, и
// «элегантно и просто» превратилось бы в «вдвое медленнее».
//
// # Почему датаграммы
//
// Предложение и отклик — это по одному пакету в каждую сторону, и терять их не жалко:
// потерялся отклик одного узла — ответит другой, потерялись все — сработает запасной путь.
// Гарантированная доставка здесь означала бы ожидание повторной передачи, а ждать в гонке
// незачем. Датаграммы привязаны к запросу по RFC 9297.
package race

import (
	"encoding/binary"
	"errors"
	"fmt"
)

// Kind — вид сообщения гонки.
type Kind uint8

const (
	// KindOffer — «есть поток, кто возьмёт».
	KindOffer Kind = 1
	// KindTake — «беру».
	KindTake Kind = 2
	// KindPass — «не мой». Отвечать отказом не обязательно, но полезно: входной узел
	// перестаёт ждать тех, кто уже отказался, и не досиживает таймаут впустую.
	KindPass Kind = 3
)

func (k Kind) String() string {
	switch k {
	case KindOffer:
		return "offer"
	case KindTake:
		return "take"
	case KindPass:
		return "pass"
	default:
		return fmt.Sprintf("kind(%d)", uint8(k))
	}
}

var (
	ErrShort       = errors.New("race: сообщение обрывается")
	ErrUnknownKind = errors.New("race: неизвестный вид сообщения")
)

// Message — предложение или отклик.
//
// В предложении нет ничего, кроме номера потока: спрашивают всех выходных узлов сразу, и
// выбирать среди них по признакам не требуется. Роль узла уже известна из журнала, а какой
// именно выход лучше — решает сама гонка.
type Message struct {
	Kind Kind
	// Flow — номер потока. Уникален в пределах входного узла и живёт только на время гонки.
	Flow uint64
}

// Encode собирает сообщение.
//
// Формат нарочно плоский: вид и номер потока, девять байт. Гонка — самая частая операция в
// сети, и разбирать её должно быть нечего.
func (m Message) Encode() ([]byte, error) {
	buf := make([]byte, 0, 1+8)
	buf = append(buf, byte(m.Kind))
	buf = binary.BigEndian.AppendUint64(buf, m.Flow)
	return buf, nil
}

// Decode разбирает сообщение.
//
// Приходит оно от опознанного узла, но опознанный не значит исправный: длина проверяется
// до того, как по ней что-то читается.
func Decode(b []byte) (Message, error) {
	if len(b) < 1+8 {
		return Message{}, ErrShort
	}
	m := Message{
		Kind: Kind(b[0]),
		Flow: binary.BigEndian.Uint64(b[1:9]),
	}
	switch m.Kind {
	case KindOffer, KindTake, KindPass:
		return m, nil
	default:
		return Message{}, fmt.Errorf("%w: %d", ErrUnknownKind, uint8(m.Kind))
	}
}
